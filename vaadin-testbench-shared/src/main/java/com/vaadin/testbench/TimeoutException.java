package com.vaadin.testbench;

/**
 * A wait ran out of time. When thrown by a {@link Wait}, the cause is the last
 * exception the wait ignored, if any.
 * <p>
 * Unchecked, unlike {@link java.util.concurrent.TimeoutException}.
 */
public class TimeoutException extends RuntimeException {

    public TimeoutException(String message) {
        super(message);
    }

    public TimeoutException(String message, Throwable cause) {
        super(message, cause);
    }
}
